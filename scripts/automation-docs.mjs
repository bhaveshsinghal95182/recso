#!/usr/bin/env node
/**
 * `docs/automation/reference.md`, generated from the registry recso serves.
 *
 *   node scripts/automation-docs.mjs          write it
 *   node scripts/automation-docs.mjs --check  fail if it is out of date
 *
 * The registry is built the way the app builds it (`registerAllMethods`),
 * from fake services, so every method, parameter, result, platform note and
 * event in the reference is the one `api.describe` returns: a method can't be
 * added, renamed or re-described without the docs following. Needs
 * `pnpm transpile:electron` first (the package scripts run it).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist-electron/automation');
const target = path.join(root, 'docs/automation/reference.md');

const load = (file) => import(pathToFileURL(path.join(dist, file)).href);
const { registerAllMethods } = await load('methods/all.js');
const { API_VERSION, MethodRegistry } = await load('registry.js');
const { fakeServices } = await load('testing.js');
const { SETTING_KEYS, SETTING_SCHEMAS, defaultSettings } = await load('settings-store.js');
const { USAGE } = await load('cli/args.js');

const registry = registerAllMethods(new MethodRegistry(), fakeServices());
const PLATFORM_NAMES = { linux: 'Linux', win32: 'Windows', darwin: 'macOS' };

function typeOf(schema) {
  if (!schema) return 'any';
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' \\| ');
  const types = Array.isArray(schema.type) ? schema.type : [schema.type ?? 'any'];
  return types
    .map((type) => (type === 'array' && schema.items ? `${typeOf(schema.items)}[]` : type))
    .join(' \\| ');
}

function paramList(schema) {
  const properties = Object.entries(schema?.properties ?? {});
  if (properties.length === 0) return ['None.'];
  const required = new Set(schema.required ?? []);
  return properties.map(([name, property]) => {
    const flag = required.has(name) ? 'required' : 'optional';
    const notes = [
      property.description,
      property.minimum !== undefined && `min ${property.minimum}`,
    ]
      .filter(Boolean)
      .join('; ');
    return `- \`${name}\` (${typeOf(property)}, ${flag})${notes ? `: ${notes}` : ''}`;
  });
}

function jsonBlock(value) {
  return ['```json', JSON.stringify(value, null, 2), '```'];
}

const defaults = defaultSettings('<Videos>');
const lines = [
  '# Automation API reference',
  '',
  '<!-- Generated by `node scripts/automation-docs.mjs` from the method registry. Do not edit by hand; `pnpm check:automation-docs` fails when this is out of date. -->',
  '',
  `API version **${API_VERSION}**. Every method is a JSON-RPC 2.0 request on the socket (Linux) or named pipe (Windows); \`recso-cli call <method> '<json params>'\` sends one, and \`recso-cli mcp\` offers each as an MCP tool named with \`_\` for \`.\`. See [README.md](README.md) for turning the API on and connecting, and [agent-guide.md](agent-guide.md) for driving recso from an agent.`,
  '',
  '## Contents',
  '',
  '- [recso-cli](#recso-cli)',
  '- [Settings](#settings)',
  '- [Methods](#methods)',
  '- [Events](#events)',
  '',
  '## recso-cli',
  '',
  '```text',
  USAGE.trimEnd(),
  '```',
  '',
  '## Settings',
  '',
  'Read with `settings.get`, changed with `settings.set`. They last until recso quits, and the recorder window shows them.',
  '',
  '| Key | Type | Default | Notes |',
  '| --- | --- | --- | --- |',
  ...SETTING_KEYS.map(
    (key) =>
      `| \`${key}\` | ${typeOf(SETTING_SCHEMAS[key])} | \`${JSON.stringify(defaults[key])}\` | ${SETTING_SCHEMAS[key].description ?? ''} |`,
  ),
  '',
  '## Methods',
  '',
];

for (const method of registry.describeMethods()) {
  lines.push(`### \`${method.name}\``, '', method.description, '');
  lines.push(`MCP tool: \`${method.name.replaceAll('.', '_')}\``, '');
  for (const [platform, note] of Object.entries(method.platforms ?? {})) {
    lines.push(`**${PLATFORM_NAMES[platform] ?? platform}:** ${note}`, '');
  }
  lines.push('Params:', '', ...paramList(method.params), '');
  lines.push(
    '<details><summary>Result schema</summary>',
    '',
    ...jsonBlock(method.result),
    '',
    '</details>',
    '',
  );
}

lines.push(
  '## Events',
  '',
  'Sent as JSON-RPC notifications to connections that called `events.subscribe` (`recso-cli events` prints them one per line), and to the hooks in `automation.json`.',
  '',
);
for (const event of registry.describeEvents()) {
  lines.push(`### \`${event.name}\``, '', event.description, '');
  lines.push(
    '<details><summary>Payload schema</summary>',
    '',
    ...jsonBlock(event.payload),
    '',
    '</details>',
    '',
  );
}

const text = `${lines.join('\n').trimEnd()}\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error(
      `${path.relative(root, target)} is out of date with the method registry; run node scripts/automation-docs.mjs`,
    );
    process.exitCode = 1;
  } else {
    console.log(`${path.relative(root, target)} matches the registry`);
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, text);
  console.log(`wrote ${path.relative(root, target)}`);
}
